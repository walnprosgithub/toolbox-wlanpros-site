#!/usr/bin/env python3
"""Print, or check, the grading block in connection-report-guide/index.html.

The cut points live in ONE place: ThroughputBands in the Toolbox app repo,
packages/net_quality/lib/src/scoring.dart. This guide lives in a different repo,
so no app test can see it. This script is the bridge: it reads the table from
that file and prints the HTML between the grading-block markers.

  python3 scripts/print-grading-block.py PATH/TO/scoring.dart           print the block
  python3 scripts/print-grading-block.py PATH/TO/scoring.dart --check   exit 1 if the guide differs

Run --check before every guide push and every Toolbox release.
"""
import re
import sys
from pathlib import Path

GUIDE = Path(__file__).resolve().parent.parent / "connection-report-guide" / "index.html"
START = "<!-- grading-block:start (generated by scripts/print-grading-block.py) -->"
END = "<!-- grading-block:end -->"
NAMES = ("downloadExcellent", "downloadGood", "downloadFair",
         "uploadExcellent", "uploadGood", "uploadFair")


def read_table(scoring_path):
    text = Path(scoring_path).read_text()
    table = {}
    for name in NAMES:
        m = re.search(r"static const double %sMbps = ([0-9.]+);" % name, text)
        if not m:
            sys.exit("ThroughputBands.%sMbps not found in %s" % (name, scoring_path))
        value = float(m.group(1))
        table[name] = int(value) if value == int(value) else value
    return table


def block(t):
    return "\n".join([
        START,
        "  <p>The Toolbox grades throughput on one set of cut points. These are the app's own bands, not a published industry standard.</p>",
        "  <ul>",
        "    <li><strong>Download</strong>: <code>Excellent</code> at %(downloadExcellent)s Mbps and up, <code>Good</code> at %(downloadGood)s and up, <code>Fair</code> at %(downloadFair)s and up, <code>Poor</code> below %(downloadFair)s.</li>" % t,
        "    <li><strong>Upload</strong>: <code>Excellent</code> at %(uploadExcellent)s Mbps and up, <code>Good</code> at %(uploadGood)s and up, <code>Fair</code> at %(uploadFair)s and up, <code>Poor</code> below %(uploadFair)s.</li>" % t,
        "    <li><strong>Summary line</strong>: the same download bands, folded into three words. <code>Strong</code> is Excellent (%(downloadExcellent)s Mbps and up), <code>Moderate</code> is Good (%(downloadGood)s to under %(downloadExcellent)s Mbps), <code>Weak</code> is Fair or Poor (under %(downloadGood)s Mbps). The Internet side is graded on the measured download. The Wi-Fi side is graded on the usable Wi-Fi estimate, on the same download bands.</li>" % t,
        "  </ul>",
        "  " + END,
    ])


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    expected = block(read_table(sys.argv[1]))
    if "--check" not in sys.argv:
        print(expected)
        return
    html = GUIDE.read_text()
    m = re.search(re.escape(START) + r".*?" + re.escape(END), html, re.S)
    if not m or m.group(0).strip() != expected.strip():
        sys.exit("DRIFT: the grading block in %s does not match the app's table" % GUIDE)
    print("ok: guide grading block matches the app's table")


if __name__ == "__main__":
    main()
